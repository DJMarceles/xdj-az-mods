"""Per-build table of the PNG images in EP147's .rodata: the only places an art patch may write.

    ep147-pngtable.py [--check] EP147_1.30 EP147_2.00
        writes azmod/ep147png.h in the source tree; --check exits 1 instead when the
        committed header differs from a fresh generation

An art set (MODS/azmod-pngpatch, or an opt-in MODS/<mod> folder) names its targets by address.
Those addresses come from a USB stick, so azmod accepts one only if it is the START of a PNG
listed here for the running EP147 build, and only for as many bytes as that image has. The
table is built from the pristine binary, never from live memory: a check that parsed the live
image could be walked by an earlier blob that planted a fake PNG with oversized chunk lengths.

Each binary (the EP147 executable of that firmware, as extracted from its update file) must
match its md5 in common/ep147build.h before anything is read. The paths may also come from
AZ_EP147_V130 / AZ_EP147_V200. A missing binary is an error, never a silently shorter table.
"""
import hashlib, os, re, struct, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "guest") if os.path.isdir(os.path.join(ROOT, "guest")) else os.path.join(ROOT, "src")
OUT = os.path.join(SRC, "azmod", "ep147png.h")
SIG = b"\x89PNG\r\n\x1a\n"
BUILDS = [("V130", "1.30", "AZ_EP147_V130"), ("V200", "2.00", "AZ_EP147_V200")]


def known_md5s():
    src = open(os.path.join(SRC, "common", "ep147build.h")).read()
    return {name: md5 for md5, name in re.findall(r'\{\s*"([0-9a-f]{32})",\s*\d+L,\s*EPB_\w+,\s*"([^"]+)"\s*\}', src)}


def rodata(b):
    shoff, = struct.unpack_from("<Q", b, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", b, 0x3A)
    secs = [struct.unpack_from("<IIQQQQIIQQ", b, shoff + i * shentsize) for i in range(shnum)]
    strtab = secs[shstrndx]
    for s in secs:
        o = strtab[4] + s[0]
        if b[o:b.index(b"\0", o)] == b".rodata":
            return s[3], s[4], s[5]          # sh_addr, sh_offset, sh_size
    sys.exit("no .rodata section")


def pngs(b):
    """[(va, length)] of every complete PNG (signature through IEND) inside .rodata, in address
    order. A signature that does not parse to an IEND inside the section is not an image."""
    addr, off, size = rodata(b)
    data = b[off:off + size]
    out, k = [], 0
    while True:
        j = data.find(SIG, k)
        if j < 0:
            return addr, size, out
        p, end = j + 8, 0
        while p + 12 <= len(data):
            ln, ty = struct.unpack_from(">I4s", data, p)
            if ln > (1 << 26):
                break
            p += 12 + ln
            if p > len(data):
                break
            if ty == b"IEND":
                end = p
                break
        if end:
            out.append((addr + j, end - j))
            k = end                          # images never overlap; a signature inside one is data
        else:
            k = j + 1


def generate(paths):
    md5s = known_md5s()
    parts = []
    counts = []
    for (sym, name, env), arg in zip(BUILDS, paths):
        path = arg or os.environ.get(env, "")
        if not path or not os.path.exists(path):
            sys.exit(f"EP147 {name}: binary not found (give its path, or set {env})")
        b = open(path, "rb").read()
        if hashlib.md5(b).hexdigest() != md5s.get(name):
            sys.exit(f"EP147 {name}: {path} is not the build ep147build.h knows (md5 differs)")
        lo, size, table = pngs(b)
        counts.append(f"{len(table)} in {name}")
        rows = []
        for i in range(0, len(table), 4):
            rows.append("    " + " ".join("{0x%x, %d}," % t for t in table[i:i + 4]))
        parts.append(f"/* EP147 {name}: .rodata [{lo:#x}, {lo + size:#x}) */\n"
                     f"static const struct ep147_png EP147_PNG_{sym}[] = {{\n" + "\n".join(rows) + "\n};\n")
    head = ("/* SPDX-License-Identifier: GPL-3.0-only */\n"
            "/* GENERATED by tools/ep147-pngtable.py. Do not edit. PNG images in EP147's .rodata\n"
            f" * ({', '.join(counts)}): start address and length of each, in address order.\n"
            " *\n"
            " * An art patch read from a stick may write only at the start of one of these images,\n"
            " * and only as many bytes as it has (ep147png_len). The table comes from the pristine\n"
            " * binary, never from live memory. */\n"
            "#ifndef EP147PNG_H\n#define EP147PNG_H\n#include <stdint.h>\n#include \"../common/ep147build.h\"\n\n"
            "struct ep147_png {\n    uint32_t va, len;\n};\n\n")
    tail = ("\n/* The length of the PNG that starts exactly at va in this build, 0 when none does\n"
            " * (an unknown build has no images). */\n"
            "static uint32_t ep147png_len(int build, uintptr_t va) {\n"
            "    const struct ep147_png *t = 0;\n"
            "    long n = 0;\n"
            "    if (build == EPB_V130) {\n"
            "        t = EP147_PNG_V130;\n"
            "        n = (long) (sizeof EP147_PNG_V130 / sizeof *EP147_PNG_V130);\n"
            "    } else if (build == EPB_V200) {\n"
            "        t = EP147_PNG_V200;\n"
            "        n = (long) (sizeof EP147_PNG_V200 / sizeof *EP147_PNG_V200);\n"
            "    }\n"
            "    long lo = 0, hi = n - 1;\n"
            "    while (lo <= hi) {\n"
            "        long mid = lo + (hi - lo) / 2;\n"
            "        if (t[mid].va == va)\n"
            "            return t[mid].len;\n"
            "        if (t[mid].va < va)\n"
            "            lo = mid + 1;\n"
            "        else\n"
            "            hi = mid - 1;\n"
            "    }\n"
            "    return 0;\n"
            "}\n#endif\n")
    return head + "\n".join(parts) + tail


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    text = generate((args + [None, None])[:2])
    if "--check" in sys.argv[1:]:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print(f"FAIL  {os.path.relpath(OUT, ROOT)} differs from a fresh tools/ep147-pngtable.py run")
            sys.exit(1)
        print(f"PASS  {os.path.relpath(OUT, ROOT)} matches the binaries")
        return
    open(OUT, "w").write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
